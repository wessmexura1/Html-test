function formatHtmlCode(source) {
    if (!source) return '';
    if (source.includes('\n')) return source.trim();
    const lines = source.trim().replace(/>\s*</g, '>\n<').split('\n');
    let depth = 0;
    return lines.map((raw) => {
        const line = raw.trim();
        if (/^<\//.test(line)) depth = Math.max(0, depth - 1);
        const output = `${'  '.repeat(depth)}${line}`;
        const opening = line.match(/^<([a-z][\w-]*)(?:\s[^>]*)?>$/i);
        const isVoid = opening && ['area','base','br','col','embed','hr','img','input','link','meta','source','track','wbr'].includes(opening[1].toLowerCase());
        if (opening && !isVoid && !line.includes(`</${opening[1]}>`)) depth += 1;
        return output;
    }).join('\n');
}
